const page = location.pathname.endsWith('teen.html') ? 'teen' : 'index';
const original = new Map();
function setLanguage(lang) {
  document.querySelectorAll('[data-lang]').forEach(b => b.classList.toggle('active', b.dataset.lang === lang));

  // Always restore the original English text first. This makes EN work
  // correctly even after switching to Hinglish.
  for (const [selector, html] of original.entries()) {
    const el = document.querySelector(selector);
    if (el) el.innerHTML = html;
  }

  // Capture the original English text for every translated element.
  const hiMap = translations[page]?.hi || {};
  for (const selector of Object.keys(hiMap)) {
    const el = document.querySelector(selector);
    if (el && !original.has(selector)) original.set(selector, el.innerHTML);
  }

  // Apply Hinglish only when HI is selected.
  if (lang === 'hi') {
    for (const [selector, value] of Object.entries(hiMap)) {
      const el = document.querySelector(selector);
      if (el) el.innerHTML = value;
    }
  }

  document.documentElement.lang = lang === 'hi' ? 'hi-Latn' : 'en';
  localStorage.setItem('funngro-language', lang);
}

document.querySelectorAll('.lang-btn').forEach(btn => btn.addEventListener('click', () => setLanguage(btn.dataset.lang)));
const saved = localStorage.getItem('funngro-language') || 'en';
setLanguage(saved);

